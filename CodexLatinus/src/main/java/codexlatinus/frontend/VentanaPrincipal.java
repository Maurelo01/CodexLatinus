    private void btnAbrirLatActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAbrirLatActionPerformed
        JFileChooser fc = new JFileChooser();
        if (fc.showOpenDialog(this) == JFileChooser.APPROVE_OPTION)
        {
            try
            {
                String contenido = Files.readString(fc.getSelectedFile().toPath());
                editor.setText(contenido);
            }
            catch (IOException e)
            {
                JOptionPane.showMessageDialog(this, "Error al abrir: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnAbrirLatActionPerformed

    private void btnGuardarPigActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarPigActionPerformed
        if (codigoPig.isEmpty())
        {
            JOptionPane.showMessageDialog(this, "No hay código PigLatin generado para guardar.");
            return;
        }
        JFileChooser fc = new JFileChooser();
        fc.setSelectedFile(new File("salida.pig"));
        if (fc.showSaveDialog(this) == JFileChooser.APPROVE_OPTION)
        {
            try
            {
                Files.writeString(fc.getSelectedFile().toPath(), codigoPig);
            }
            catch (IOException e)
            {
                JOptionPane.showMessageDialog(this, "Error al guardar: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnGuardarPigActionPerformed

    private void btnCompilarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCompilarActionPerformed
        String codigo = editor.getText();
        areaSalida.setText("");
        areaAST.setText("");
        areaTabla.setText("");
        CharStream input = CharStreams.fromString(codigo);
        CodexLatinusLexer lexer = new CodexLatinusLexer(input);
        CommonTokenStream tokens = new CommonTokenStream(lexer);
        CodexLatinusParser parser = new CodexLatinusParser(tokens);
        parser.removeErrorListeners();
        
        parser.addErrorListener(new BaseErrorListener()
        {
            @Override
            public void syntaxError(Recognizer<?, ?> recognizer, Object offendingSymbol, int line, int charPositionInLine, String msg, RecognitionException e) 
            {
                areaSalida.append(String.format("Error sintáctico línea %d:%d - %s%n", line, charPositionInLine + 1, msg));
            }
        });
        ParseTree tree = parser.programa();
        if (parser.getNumberOfSyntaxErrors() > 0)
        {
            areaSalida.append("Se encontraron errores de sintaxis.\n");
            arbolActual = null;
            btnTraducirPig.setEnabled(false);
            return;
        }
        MiVisitor visitor = new MiVisitor();
        visitor.visit(tree);
        if (visitor.getErroresSemanticos() > 0)
        {
            areaSalida.append("Se encontraron " + visitor.getErroresSemanticos() + " errores semánticos.\n");
            arbolActual = null;
            btnTraducirPig.setEnabled(false);
            return;
        }
        this.arbolActual = tree;
        GeneradorASTDOT astGen = new GeneradorASTDOT();
        String astDOT = astGen.generarDOT(tree);
        areaAST.setText(astDOT);
        GeneradorSimbolosDOT simGen = new GeneradorSimbolosDOT();
        String simDOT = simGen.generarDOT(visitor.getTablaSimbolos());
        areaTabla.setText(simDOT);

        // Capturar pila de procesos
        ParseTreeWalker walker = new ParseTreeWalker();
        ParseTraceListener traceListener = new ParseTraceListener();
        walker.walk(traceListener, tree);
        this.pasos = traceListener.getPasos();

        areaSalida.setText("Programa válido. Se puede traducir a PigLatin.");
        btnTraducirPig.setEnabled(true);
    }//GEN-LAST:event_btnCompilarActionPerformed

